// Self-hosted faces of the official site (DEV-303, PR B): the font files
// next/font/google downloaded at build time for app/layout.tsx (Shippori Mincho
// 400/600, Noto Sans JP 400/500/600, Zen Maru Gothic 500/700), committed to
// app/_fonts/ so the build needs no network. Shared code and the file policy:
// local-fonts.mjs.
//
//   node scripts/fonts/generate-site-fonts.mjs --packs <dir with the .tgz files>
//       network: fetches the CSS and files from Google Fonts, copies each LICENSE,
//       and writes app/_fonts/manifest.json and app/_fonts/site-fonts.generated.ts
//   node scripts/fonts/generate-site-fonts.mjs --check
//       offline: the module is what the manifest renders to, and every committed
//       font file matches the manifest (also a unit test)
//
// Faces, order and descriptors are Google's, as before. Noto Sans JP is one
// variable file per subset that Google lists under 400, 500 and 600: one
// committed file, three @font-face rules, as before.
//
// Preloads (owner-approved change): next/font/google preloaded 243 files
// (~5.6 MB) on every page, because Google labels only the Latin subsets and
// next/font carries the last label onto the following unlabelled Japanese
// subsets. Now only the Latin subsets the pages use at first view are
// preloaded: Shippori Mincho 600 (headings) and Noto Sans JP (body text, one file
// for its three weights). Shippori Mincho 400 and Zen Maru Gothic are not used
// by the official pages at first view and load on demand, as every Japanese
// subset does.

