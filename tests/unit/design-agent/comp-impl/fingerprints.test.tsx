import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Browser } from "playwright";
import { renderToStaticMarkup } from "react-dom/server";
import { afterAll, beforeAll, describe, expect, it, vi } from "vitest";
import ProfileRenderer from "@/components/demo/profile/ProfileRenderer";
import { renderDemo } from "@/components/demo/renderDemo";
import { loadHandWritten, parseShop } from "@/lib/design-agent/compare/shops";
import { fingerprintDistance } from "@/lib/design-agent/comp-impl/anti-template";
import { fingerprintOf } from "@/lib/design-agent/comp-impl/render";
import { REFERENCES_PATH } from "@/lib/design-agent/comp-impl/run";
import { CATEGORY_DEFAULT_PROFILES } from "@/lib/design-agent/defaults";
import { DIRECTIONS } from "@/lib/design-agent/profile";
import type { DemoView } from "@/lib/sales/demo-content";
import { FACTS_SOURCE, launch, REPO } from "./support";

// DEV-082: the anti-template guard's reference fingerprints are the existing
// demo templates and the profile renderer (category defaults, every direction,
// the hand-written Stage 1 specs), rendered here with the fictional wagashi
// facts. The committed file must equal what the current components render, so
// it can never go stale; UPDATE_COMP_FINGERPRINTS=1 rewrites it.

vi.setConfig({ testTimeout: 120_000 });

let browser: Browser;
beforeAll(async () => {
  browser = await launch();
});
afterAll(async () => {
  await browser?.close();
});

const page = (body: string) => `<!doctype html><html lang="ja"><head><meta charset="utf-8"></head><body>${body}</body></html>`;

async function references(): Promise<Array<{ id: string; html: string }>> {
  const shop = parseShop(JSON.parse(readFileSync(FACTS_SOURCE, "utf8")) as unknown)!;
  const demo: DemoView = shop.demo;
  const out: Array<{ id: string; html: string }> = [];
  for (const [template, category] of [["bakery_v1", "bakery"], ["baked_goods_v1", "baked_goods"], ["cafe_v1", "cafe"]] as const) {
    out.push({ id: `template:${template}`, html: page(renderToStaticMarkup(renderDemo({ ...demo, template, category }))) });
  }
  for (const [category, profile] of Object.entries(CATEGORY_DEFAULT_PROFILES)) out.push({ id: `profile:default:${category}`, html: page(renderToStaticMarkup(<ProfileRenderer demo={demo} profile={profile} />)) });
  for (const direction of DIRECTIONS) out.push({ id: `profile:direction:${direction}`, html: page(renderToStaticMarkup(<ProfileRenderer demo={demo} profile={{ ...CATEGORY_DEFAULT_PROFILES.baked_goods, direction }} />)) });
  const hand = await loadHandWritten(join(REPO, "scripts/sales-design-worker/compare/hand-written"), ["coffee", "patisserie", "wagashi"]);
  for (const [key, profile] of Object.entries(hand)) out.push({ id: `profile:hand-written:${key}`, html: page(renderToStaticMarkup(<ProfileRenderer demo={demo} profile={profile} />)) });
  return out;
}

describe("anti-template reference fingerprints", () => {
  it("the committed file equals the fingerprints of the current templates and renderer", async () => {
    const refs = [];
    for (const r of await references()) refs.push({ id: r.id, fingerprint: await fingerprintOf(browser, r.html) });
    const file = join(REPO, REFERENCES_PATH);
    const fresh = `${JSON.stringify({ note: "DEV-082 anti-template references; generated by tests/unit/design-agent/comp-impl/fingerprints.test.tsx (UPDATE_COMP_FINGERPRINTS=1). Do not edit by hand.", references: refs })}\n`;
    if (process.env.UPDATE_COMP_FINGERPRINTS === "1") writeFileSync(file, fresh);
    expect(readFileSync(file, "utf8")).toBe(fresh);
  });

  it("a template is at distance 0 from itself and the synthetic page is far from every reference", async () => {
    const refs = await references();
    const a = await fingerprintOf(browser, refs[0]!.html);
    expect(fingerprintDistance(a, a)).toBe(0);
    const mine = await fingerprintOf(browser, readFileSync(join(REPO, "scripts/sales-design-worker/comp-impl/synthetic-wagashi/page/index.html"), "utf8"));
    const distances = [];
    for (const r of refs) distances.push(fingerprintDistance(mine, await fingerprintOf(browser, r.html)));
    console.log("synthetic page: nearest reference distance", Math.min(...distances));
    expect(Math.min(...distances)).toBeGreaterThan(0.35);
  });
});
