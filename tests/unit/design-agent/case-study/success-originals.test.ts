function privateRoot(files: Record<string, Buffer>): string {
  const root = tmp("sr-orig-root-");
  for (const [rel, data] of Object.entries(files)) {
    mkdirSync(join(root, rel, ".."), { recursive: true });
    writeFileSync(join(root, rel), data);
  }
  return root;
}

describe("readZip / SHA256SUMS", () => {
  it("reads stored and deflated entries and checks every SHA256SUMS line", () => {
    const r = readZip(B_ZIP);
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    expect(r.entries.map((e) => e.name)).toEqual(["site/index.html", "site/desktop_full.png", "SHA256SUMS"]);
    expect(r.entries[0]!.data.equals(B_PAGE)).toBe(true);
    expect(checkSha256Sums(r.entries)).toEqual({ present: true, listed: 2, matched: 2, mismatched: 0, missing: 0 });
  });
  it.each([
    ["crc_mismatch", [{ name: "a.png", data: png("x"), badCrc: true }]],
    ["unsafe_name", [{ name: "../escape.png", data: png("x") }]],
    ["unsafe_name", [{ name: "a\\b.png", data: png("x") }]],
    ["encrypted", [{ name: "a.png", data: png("x"), flags: 1 }]],
    ["link_entry", [{ name: "link", data: Buffer.from("/etc/passwd"), external: (0o120777 << 16) >>> 0 }]],
    ["duplicate_name", [{ name: "A.png", data: png("x") }, { name: "a.png", data: png("y") }]],
  ])("refuses %s", (reason, entries) => {
    expect(readZip(zip(entries))).toEqual({ ok: false, reason });
  });
  it("refuses bytes that are not a ZIP", () => expect(readZip(png("x"))).toEqual({ ok: false, reason: "not_a_zip" }));
  it("finds a SHA256SUMS mismatch and a missing listed file", () => {
    const r = readZip(zip([{ name: "a.png", data: png("a") }, { name: "SHA256SUMS", data: Buffer.from(`${sha("other")}  a.png\n${sha("x")}  gone.png\n`) }]));
    expect(r.ok && checkSha256Sums(r.entries)).toEqual({ present: true, listed: 2, matched: 0, mismatched: 1, missing: 1 });
  });
  it("member names: relative, no dot segments, no backslash or colon", () => {
    expect(safeMemberName("site/a.png")).toBe(true);
    for (const bad of ["/abs", "a/../b", "./a", "a//b", "c:x", "a\u0001"]) expect(safeMemberName(bad)).toBe(false);
  });
});

